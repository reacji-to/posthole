// Registers the native helper with Helium (and Chrome/Chromium if present) so
// the extension can write files. Run once per machine: npm run install-host
//   --dir <path>   install the manifest into one specific NativeMessagingHosts folder
//   --uninstall    remove the manifests again
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HOST = 'com.imbue.posthole';
const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const uninstall = args.includes('--uninstall');
const customDir = args.includes('--dir') ? args[args.indexOf('--dir') + 1] : null;

// The manifest "key" pins the extension ID, so an unpacked load always matches.
export function extensionId(key) {
  const digest = crypto.createHash('sha256').update(Buffer.from(key, 'base64')).digest('hex').slice(0, 32);
  return [...digest].map(c => String.fromCharCode(97 + parseInt(c, 16))).join('');
}

function browserDirs() {
  const home = os.homedir();
  const candidates = process.platform === 'darwin'
    ? ['net.imput.helium', 'Google/Chrome', 'Google/Chrome Beta', 'Google/Chrome Canary', 'Chromium', 'BraveSoftware/Brave-Browser']
      .map(name => path.join(home, 'Library/Application Support', name))
    : ['net.imput.helium', 'google-chrome', 'chromium', 'BraveSoftware/Brave-Browser'].map(name => path.join(home, '.config', name));
  return candidates.filter(dir => fs.existsSync(dir)).map(dir => path.join(dir, 'NativeMessagingHosts'));
}

const key = JSON.parse(fs.readFileSync(path.join(repo, 'manifest.json'), 'utf8')).key;
const id = extensionId(key);
const targets = customDir ? [path.resolve(customDir)] : browserDirs();
const wrapper = path.join(repo, 'host', 'posthole-host');

if (uninstall) {
  for (const dir of targets) fs.rmSync(path.join(dir, `${HOST}.json`), { force: true });
  console.log(`Removed ${HOST} from:\n  ${targets.join('\n  ')}`);
  process.exit(0);
}

// Browsers launch helpers with a minimal PATH, so pin the node that ran this script.
fs.writeFileSync(wrapper, `#!/bin/sh
# Generated by \`npm run install-host\`. Browsers start native helpers with a
# minimal PATH, so this pins the node binary that ran the installer.
NODE="${process.execPath}"
[ -x "$NODE" ] || NODE="$(command -v node || echo /opt/homebrew/bin/node)"
exec "$NODE" "${path.join(repo, 'host', 'posthole-host.mjs')}" "$@"
`, { mode: 0o755 });

const manifest = {
  name: HOST,
  description: 'posthole file writer',
  path: wrapper,
  type: 'stdio',
  allowed_origins: [`chrome-extension://${id}/`],
};
if (!targets.length) {
  console.error('No Helium/Chrome profile folder found. Pass --dir <NativeMessagingHosts folder>.');
  process.exit(1);
}
for (const dir of targets) {
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, `${HOST}.json`), `${JSON.stringify(manifest, null, 2)}\n`);
}
console.log(`Extension ID: ${id}\nHelper: ${wrapper}\nRegistered in:\n  ${targets.join('\n  ')}`);
